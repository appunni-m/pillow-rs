//! Module fns operation registration.
use super::prelude::{PilError, Registry};
fn register_merge_blend(m: &mut Registry) {
    // Merge packs the remaining single-band images into one auxiliary storage
    // range. The GPU planner validates the band count, modes, and dimensions
    // before constructing that range, so this shader only interleaves validated
    // bytes.
    m.insert(
        "Merge",
        gpu_entry!(
            crate::compute::pool_cpu::ops::composite::ops::prepare_merge_pipeline,
            "merge.wgsl"
        ),
    );

    m.insert(
        "BlendModule",
        gpu_entry!(
            crate::compute::pool_cpu::ops::composite::ops::prepare_blend_pipeline,
            "blend_module.wgsl"
        ),
    );
}

fn register_composite_eval(m: &mut Registry) {
    m.insert(
        "CompositeModule",
        gpu_entry!(
            crate::compute::pool_cpu::ops::composite::ops::prepare_composite_pipeline,
            "composite_module.wgsl"
        ),
    );

    m.insert(
        "Eval",
        gpu_entry!(
            crate::compute::pool_cpu::ops::eval::ops::prepare_pipeline,
            "eval.wgsl"
        ),
    );
}

fn register_part_2(m: &mut Registry) {
    m.insert(
        "EffectNoise",
        // Pillow's effect consumes one sequential libc RNG stream with a
        // rejection loop and returns a new L image. The GPU path uploads the
        // exact host-generated bytes and only performs the packed transport
        // gather, keeping the process-global stream deterministic.
        gpu_entry!(
            crate::compute::pool_cpu::ops::effects::ops::prepare_noise_pipeline,
            "effect_noise.wgsl"
        ),
    );
}

pub(super) fn register(m: &mut Registry) -> Result<(), PilError> {
    register_merge_blend(m);
    register_composite_eval(m);
    register_part_2(m);
    Ok(())
}
