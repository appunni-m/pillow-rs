    def _enhance_contrast():
        ImageEnhance.Contrast(_load_rgb()).enhance(1.5)

    reg("ImageEnhance.Contrast", _enhance_contrast)

    def _enhance_sharpness():
        ImageEnhance.Sharpness(_load_rgb()).enhance(2.0)

    reg("ImageEnhance.Sharpness", _enhance_sharpness)

