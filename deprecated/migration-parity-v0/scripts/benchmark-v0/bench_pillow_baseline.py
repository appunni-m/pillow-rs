def main():
    parser = argparse.ArgumentParser(description="Benchmark Pillow operations for speedup baseline")
    parser.add_argument("--runs", type=int, default=30, help="Number of runs per function")
    parser.add_argument("--warmup", type=int, default=3, help="Number of warmup runs per function")
    parser.add_argument("--output", type=str, default=str(OUT_FILE), help="Output JSON path")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out_path = Path(args.output)

    print(f"Pillow baseline benchmark -- {args.runs} runs, {args.warmup} warmup iterations")
    print(f"Pillow version: {Image.__version__}")
    print(f"Output: {out_path.resolve()}")
    print()

    specs = build_bench_specs(args.runs, args.warmup)
    results = list(specs.values())
    results.sort(key=lambda r: r["function"])

    # Summary
    total_time = sum(r["mean_s"] for r in results)
    print(f"Completed {len(results)} benchmark functions")
    print(f"Total time: {total_time:.3f}s")
    print(f"Fastest:  {min(results, key=lambda r: r['mean_s'])['function']} "
          f"({min(r['mean_s'] for r in results)*1000:.2f}ms)")
    print(f"Slowest:  {max(results, key=lambda r: r['mean_s'])['function']} "
          f"({max(r['mean_s'] for r in results)*1000:.2f}ms)")

    # Meta
    meta = {
        "benchmark": "pillow_baseline",
        "pillow_version": Image.__version__,
        "runs_per_function": args.runs,
        "warmup_per_function": args.warmup,
        "num_functions": len(results),
        "total_time_s": total_time,
    }
    payload = {"meta": meta, "results": results}

    out_path.write_text(json.dumps(payload, indent=2))
    print(f"\nSaved: {out_path}")


if __name__ == "__main__":
    main()
