REF_1K = REF_DIR / "ref_1k.png"
REF_GRAY = REF_DIR / "ref_grayscale.png"


def _load_ref(path, fallback_mode="RGB", fallback_size=(1024, 1024)):
    """Load a reference image, or create a synthetic fallback."""
    if path.exists():
        return Image.open(path).convert(fallback_mode)
    # Deterministic fallback
    im = Image.new(fallback_mode, fallback_size)
    for y in range(fallback_size[1]):
        for x in range(fallback_size[0]):
            r = (x * 37 + y * 113) & 0xFF
            g = (x * 59 + y * 211) & 0xFF
            b = (x * 97 + y * 179) & 0xFF
            if fallback_mode == "RGBA":
                a = (x * 13 + y * 71) & 0xFF
                im.putpixel((x, y), (r, g, b, a))
            elif fallback_mode == "L":
                im.putpixel((x, y), (r * 77 + g * 150 + b * 29) // 256)
            else:
                im.putpixel((x, y), (r, g, b))
    return im


def _load_rgb():
    return _load_ref(REF_2K, "RGB", (2048, 1536))


def _load_rgba():
    return _load_ref(REF_1K, "RGBA", (1024, 1024))


def _load_gray():
    return _load_ref(REF_GRAY, "L", (1024, 1024))


# ---------------------------------------------------------------------------
# Benchmarking helpers
# ---------------------------------------------------------------------------

class Timer:
    """Simple timer using timeit.default_timer."""

    def __init__(self):
        self._start = None

    def start(self):
        self._start = timeit.default_timer()

    def stop(self):
        return timeit.default_timer() - self._start


def _bench_op(name, op_fn, runs, warmup):
    """Benchmark a function that takes no arguments (op_fn()).

    Times 'runs' iterations, returning min, max, median, mean, stdev.
    """
    # Warmup
    for _ in range(warmup):
        op_fn()

    times = []
    for _ in range(runs):
        t = Timer()
        t.start()
        op_fn()
        elapsed = t.stop()
        times.append(elapsed)

    return _summarize(name, times)


def _summarize(name, times):
    """Compute summary statistics from a list of times (seconds)."""
    n = len(times)
    total = sum(times)
    mean = total / n
    sorted_t = sorted(times)
    median = sorted_t[n // 2]
    variance = sum((t - mean) ** 2 for t in times) / n
    stdev = variance ** 0.5
    return {
        "function": name,
        "runs": n,
        "min_s": sorted_t[0],
        "max_s": sorted_t[-1],
        "median_s": median,
        "mean_s": mean,
        "stdev_s": stdev,
    }


