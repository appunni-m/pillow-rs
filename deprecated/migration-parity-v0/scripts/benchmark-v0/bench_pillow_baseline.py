    def _open_save():
        im = _load_rgb()
        buf = Path(OUT_DIR) / "_tmp_bench_open_save.jpg"
        im.save(buf, format="JPEG", quality=85)
        buf.unlink(missing_ok=True)

    reg("open_save", _open_save)

    # resize
    def _resize():
        _load_rgb().resize((800, 600), Image.LANCZOS)

    reg("resize", _resize)

    # crop
    def _crop():
        _load_rgb().crop((100, 100, 1100, 900))

    reg("crop", _crop)

    # rotate
    def _rotate():
        _load_rgb().rotate(45, resample=Image.BICUBIC, expand=True)

    reg("rotate", _rotate)

    # transpose
    def _transpose():
        _load_rgb().transpose(Image.Transpose.FLIP_LEFT_RIGHT)

    reg("transpose", _transpose)

    # thumbnail
    def _thumbnail():
        im = _load_rgb()
        im.thumbnail((256, 256), Image.LANCZOS)

    reg("thumbnail", _thumbnail)

    # to_bytes
    def _to_bytes():
        _load_rgb().tobytes()

    reg("to_bytes", _to_bytes)

    # new (create image)
    def _new():
        Image.new("RGB", (2048, 1536), (128, 128, 128))

    reg("new", _new)

    # convert
    def _convert():
        _load_rgb().convert("L")

    reg("convert", _convert)

    # paste (image onto image, no mask)
    def _paste():
        dst = _load_rgb()
        src = Image.new("RGB", (512, 512), (255, 0, 0))
        dst.paste(src, (100, 100))

    reg("paste", _paste)

    # paste with mask
    def _paste_mask():
        dst = _load_rgba()
        src = Image.new("RGBA", (256, 256), (0, 255, 0))
        mask = Image.new("L", (256, 256), 128)
        dst.paste(src, (50, 50), mask)

    reg("paste_mask", _paste_mask)

    # paste with color fill
    def _paste_color():
        dst = _load_rgb()
        dst.paste((255, 0, 0), (200, 200, 600, 600))

    reg("paste_color", _paste_color)

    # filter (generic -- use BLUR as common)
    def _filter():
        _load_rgb().filter(ImageFilter.BLUR)

    reg("filter", _filter)

    # copy
    def _copy():
        _load_rgb().copy()

    reg("copy", _copy)

    # split
    def _split():
        _load_rgba().split()

    reg("split", _split)

    # getbands
    def _getbands():
        _load_rgb().getbands()

    reg("getbands", _getbands)

    # getbbox
    def _getbbox():
        _load_rgb().getbbox()

    reg("getbbox", _getbbox)

    # getcolors
    def _getcolors():
        _load_rgb().getcolors(maxcolors=256)

    reg("getcolors", _getcolors)

    # getextrema
    def _getextrema():
        _load_rgb().getextrema()

    reg("getextrema", _getextrema)

    # getpixel
    def _getpixel():
        _load_rgb().getpixel((500, 500))

    reg("getpixel", _getpixel)

    # getprojection
    def _getprojection():
        _load_gray().getprojection()

    reg("getprojection", _getprojection)

    # histogram
    def _histogram():
        _load_rgb().histogram()

    reg("histogram", _histogram)

    # point
    def _point():
        _load_gray().point(lambda x: min(255, x * 2))

    reg("point", _point)

    # putalpha
    def _putalpha():
        im = _load_rgba()
        alpha = Image.new("L", im.size, 128)
        im.putalpha(alpha)

    reg("putalpha", _putalpha)

    # putpixel
    def _putpixel():
        im = _load_rgb()
        im.putpixel((0, 0), (255, 0, 0))

    reg("putpixel", _putpixel)

