def _make_color(mode):
    if mode == "L": return 128
    if mode == "LA": return (128, 255)
    if mode == "RGB": return (255, 0, 0)
    if mode == "RGBA": return (255, 0, 0, 255)
    if mode == "1": return 1
    if mode == "P": return None  # needs convert
    if mode == "CMYK": return None
    if mode == "YCbCr": return None
    if mode == "HSV": return None
    if mode == "I": return 128
    if mode == "F": return 0.5
    return 128


def _make_image(mode, size=(30, 30)):
    c = _make_color(mode)
    if c is None:
        return Image.new("RGB", size, (255, 0, 0)).convert(mode)
    return Image.new(mode, size, c)


