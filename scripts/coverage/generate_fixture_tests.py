#!/usr/bin/env python3
"""Generate WASM parity test file from fixture index.

Reads tests/fixtures/index.json and generates a JS test file
with @covers JSDoc annotations for each operation × mode × target combination.
The generated test loads the fixture, runs the WASM operation, and compares hashes.

Usage: python scripts/coverage/generate_fixture_tests.py
Output: pillow-rs-js/tests/generated_parity.test.mjs
"""
import json
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parent.parent.parent
FIXTURES_DIR = ROOT / "pillow-rs-js" / "tests" / "fixtures"
OUTPUT = ROOT / "pillow-rs-js" / "tests" / "generated_parity.test.mjs"

index = {}
index_path = FIXTURES_DIR / "index.json"
if index_path.exists():
    with open(index_path) as f:
        index = json.load(f).get("operations", {})

# Group by op for readability
by_op = defaultdict(list)
for key, fixture in index.items():
    by_op[fixture["op"]].append((key, fixture))

lines = []
lines.append("/**")
lines.append(" * GENERATED FILE — do not edit directly.")
lines.append(" * Generated by: scripts/coverage/generate_fixture_tests.py")
lines.append(" * ")
lines.append(" * Each test loads a JSON fixture (pre-computed PIL reference hash),")
lines.append(" * runs the WASM operation, and compares output hashes.")
lines.append(" * ")
lines.append(" * @covers annotations are parsed by scripts/coverage/validate_coverage.py")
lines.append(" * for enforced coverage tracking across Python + JS targets.")
lines.append(" */")
lines.append("")
lines.append("import {{ readFileSync }} from 'fs';")
lines.append("import {{ fileURLToPath }} from 'url';")
lines.append("import {{ dirname, join }} from 'path';")
lines.append("import {{ createHash }} from 'crypto';")
lines.append("")
lines.append("const __dirname = dirname(fileURLToPath(import.meta.url));")
lines.append("const FIXTURES = join(__dirname, 'fixtures');")
lines.append("")
lines.append("function hash(bytes) {{")
lines.append("    return createHash('sha256').update(Buffer.from(bytes)).digest('hex');")
lines.append("}}")
lines.append("")
lines.append("function loadFixture(name) {{")
lines.append("    return JSON.parse(readFileSync(join(FIXTURES, name), 'utf8'));")
lines.append("}}")
lines.append("")
lines.append("let wasm;")
lines.append("")
lines.append("beforeAll(async () => {{")
lines.append("    wasm = await import(join(__dirname, '..', 'pkg', 'pillow_rs_js.js'));")
lines.append("    await wasm.default();")
lines.append("}});")
lines.append("")

# Generate test functions
for op_name in sorted(by_op.keys()):
    items = by_op[op_name]
    safe_op = op_name.replace(".", "_")

    lines.append(f"// ── {op_name} ──")
    for key, fixture in sorted(items):
        mode = fixture["mode"]
        target = fixture["target"]
        expected_hash = fixture["expectedHash"]

        # @covers JSDoc annotation
        lines.append("/**")
        lines.append(f" * @covers {op_name}")
        lines.append(f" * @mode {mode}")
        lines.append(f" * @target {target}")
        lines.append(" */")
        lines.append(f"test('{op_name} × {mode} × {target}', async () => {{")
        lines.append(f"    const fixture = loadFixture('{key}.json');")
        lines.append(f"    const img = createImage(fixture.op, fixture.mode);")
        lines.append(f"    const result = runOp(img, fixture.op);")
        lines.append(f"    if (!result) {{ return; }} // skip unsupported")
        lines.append(f"    const actualHash = hash(result);")
        lines.append(f"    expect(actualHash).toBe(fixture.expectedHash);")
        lines.append(f"}});")
        lines.append("")

# Add helpers
lines.append("// ── Helpers ──")
lines.append("")
lines.append("function createImage(op, mode) {")
lines.append("    const size = [30, 30];")
lines.append("    switch (mode) {")
lines.append("        case 'L': return new wasm.Image('L', size[0], size[1], 128, 128, 128, 255);")
lines.append("        case 'LA': return new wasm.Image('LA', size[0], size[1], 128, 128, 128, 255);")
lines.append("        case 'RGB': return new wasm.Image('RGB', size[0], size[1], 255, 0, 0, 255);")
lines.append("        case 'RGBA': return new wasm.Image('RGBA', size[0], size[1], 255, 0, 0, 255);")
lines.append("        case '1': return new wasm.Image('1', size[0], size[1], 1, 1, 1, 255);")
lines.append("        case 'P': return new wasm.Image('RGB', size[0], size[1], 255, 0, 0, 255);")
lines.append("        case 'CMYK':")
lines.append("        case 'YCbCr':")
lines.append("        case 'HSV':")
lines.append("        case 'I':")
lines.append("        case 'F': return new wasm.Image('RGB', size[0], size[1], 255, 0, 0, 255);")
lines.append("        default: return new wasm.Image('RGB', size[0], size[1], 255, 0, 0, 255);")
lines.append("    }")
lines.append("}")
lines.append("")
lines.append("function runOp(img, op) {")
lines.append("    const [_, func] = op.split('.');")
lines.append("    switch (func) {")
lines.append("        case 'resize': return img.resize(15, 15);")
lines.append("        case 'crop': return img.crop(5, 5, 25, 25);")
lines.append("        case 'rotate': return img.rotate(90);")
lines.append("        case 'transpose': return img.transpose('FLIP_LEFT_RIGHT');")
lines.append("        case 'filter': return img.filter('BLUR');")
lines.append("        case 'convert': return img.convert('RGB');")
lines.append("        case 'copy': return img.copy();")
lines.append("        case 'thumbnail': img.thumbnail(15, 15); return img;")
lines.append("        case 'quantize': return img.quantize(16);")
lines.append("        case 'tobytes': return img.toBytes();")
lines.append("        default: return img;")
lines.append("    }")
lines.append("}")

output = '\n'.join(lines) + '\n'

# Only write if fixtures exist
if index:
    OUTPUT.write_text(output)
    print(f"Generated {OUTPUT}")
    print(f"  {sum(1 for l in output.split(chr(10)) if '@covers' in l)} @covers annotations")
    print(f"  {len(by_op)} operations covered")
else:
    print("No fixtures found — run generate_fixtures.py first")
