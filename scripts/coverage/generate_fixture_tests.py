#!/usr/bin/env python3
"""Generate test_fixture_parity.py from fixture index.

Reads tests/fixtures/index.json and generates a static Python test file
with @pytest.mark.covers annotations using STRING LITERALS so
validate_coverage.py's regex scanner can find them.

Handles both expectedHash (image output) and expectedValue (non-image
return) fixtures.

Usage: python scripts/coverage/generate_fixture_tests.py
Output: tests/test_fixture_parity.py
"""
import json
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parent.parent.parent
FIXTURES_DIR = ROOT / "tests" / "fixtures"
OUTPUT = ROOT / "tests" / "test_fixture_parity.py"

index = {}
index_path = FIXTURES_DIR / "index.json"
if index_path.exists():
    with open(index_path) as f:
        index = json.load(f).get("operations", {})

# Group by op for readability
by_op = defaultdict(list)
for key, fixture in index.items():
    by_op[fixture["op"]].append((key, fixture))


def _esc(s):
    """Escape a string for Python source code."""
    return json.dumps(s)


lines = []
lines.append('"""Fixture-based parity tests — static @covers markers for coverage validation.')
lines.append("")
lines.append("GENERATED FILE — do not edit directly.")
lines.append("Generated by: scripts/coverage/generate_fixture_tests.py")
lines.append("")
lines.append("Each parametrized test loads a JSON fixture (PIL reference),")
lines.append("runs the RSPIL operation, and compares output.")
lines.append("")
lines.append("@pytest.mark.covers markers are STATIC STRING LITERALS so")
lines.append("validate_coverage.py can parse them with regex.")
lines.append('"""')
lines.append("import json, hashlib")
lines.append("from pathlib import Path")
lines.append("import pytest")
lines.append("from pillow_rs import Image, ImageOps, ImageChops, ImageDraw, ImageEnhance")
lines.append("")
lines.append("FIXTURES_DIR = Path(__file__).parent / 'fixtures'")
lines.append("")
lines.append("")
lines.append("def _load_fixture(name):")
lines.append('    with open(FIXTURES_DIR / name) as f:')
lines.append("        return json.load(f)")
lines.append("")
lines.append("")
lines.append("def _hash(data):")
lines.append("    return hashlib.sha256(data).hexdigest()")
lines.append("")
lines.append("")
lines.append("_REF = None")
lines.append("")
lines.append("")
lines.append("def _get_reference():")
lines.append('    """Load the same complex reference image as the fixture generator."""')
lines.append("    global _REF")
lines.append("    if _REF is None:")
lines.append('        ref_path = Path(__file__).parent / "test_reference.png"')
lines.append("        _REF = Image.open(str(ref_path)).resize((100, 100))")
lines.append("    return _REF.copy()")
lines.append("")
lines.append("")
lines.append("def _create_image(mode):")
lines.append('    """Create RSPIL image from complex reference."""')
lines.append("    ref = _get_reference()")
lines.append('    if mode == "RGB": return ref')
lines.append('    if mode == "RGBA": return ref.convert("RGBA")')
lines.append('    if mode == "L": return ref.convert("L")')
lines.append('    if mode == "LA": return ref.convert("LA")')
lines.append('    if mode == "1": return ref.convert("1")')
lines.append('    if mode == "P": return ref.convert("P")')
lines.append('    if mode == "CMYK": return ref.convert("CMYK") if hasattr(ref, "convert") else ref')
lines.append('    if mode == "YCbCr": return ref.convert("YCbCr") if hasattr(ref, "convert") else ref')
lines.append('    if mode == "HSV": return ref.convert("HSV") if hasattr(ref, "convert") else ref')
lines.append('    if mode == "I": return ref.convert("I") if hasattr(ref, "convert") else ref')
lines.append('    if mode == "F": return ref.convert("F") if hasattr(ref, "convert") else ref')
lines.append("    return ref")
lines.append("")
lines.append("")
lines.append("def _run_op(img, op):")
lines.append('    """Run the operation, matching fixture generator parameters."""')
lines.append('    _, func = op.split(".")')
lines.append('    if func == "resize": return img.resize((50, 50))')
lines.append('    if func == "crop": return img.crop((25, 25, 75, 75))')
lines.append('    if func == "rotate": return img.rotate(90)')
lines.append('    if func == "transpose": return img.transpose(0)')
lines.append('    if func == "filter": return img.filter("BLUR")')
lines.append('    if func == "convert":')
lines.append('        return img.convert("RGB") if img.mode != "RGB" else img.convert("L")')
lines.append('    if func == "copy": return img.copy()')
lines.append('    if func == "thumbnail": img.thumbnail((50, 50)); return img')
lines.append('    if func == "quantize": return img.quantize(16)')
lines.append('    if func == "tobytes": return img.tobytes()')
lines.append('    if func == "split": return img.split()[0] if img.split() else None')
lines.append('    if func == "getbands": return img.getbands()')
lines.append('    if func == "getbbox": return img.getbbox()')
lines.append('    if func == "getextrema": return img.getextrema()')
lines.append('    if func == "histogram": return img.histogram()')
lines.append('    if func == "getpixel": return img.getpixel((50, 50))')
lines.append('    if func == "getcolors": return img.getcolors(256)')
lines.append('    if func == "getdata": return img.getdata()')
lines.append('    if func == "getprojection": return img.getprojection()')
lines.append('    if func == "entropy": return img.entropy()')
lines.append('    if func == "load": img.load(); return None')
lines.append('    if func == "close": img.close(); return None')
lines.append('    if func == "verify": img.verify(); return None')
lines.append('    if func == "seek": img.seek(0); return None')
lines.append('    if func == "tell": return img.tell()')
lines.append('    if func == "paste":')
lines.append('        p = _create_image("RGB")')
lines.append("        img.paste(p, (0, 0))")
lines.append("        return img")
lines.append('    if func == "alpha_composite":')
lines.append('        fg = _create_image("RGBA")')
lines.append("        img.alpha_composite(fg)")
lines.append("        return img")
lines.append('    if func == "point": return img.point([min(255, i+50) for i in range(256)])')
lines.append('    if func == "putalpha": img.putalpha(128); return img')
lines.append('    if func == "putdata":')
lines.append("        n = img.width * img.height")
lines.append("        img.putdata([128] * n)")
lines.append("        return img")
lines.append('    if func == "reduce": return img.reduce(2)')
lines.append('    if func == "effect_spread": return img.effect_spread(2)')
lines.append('    if func == "transform": return img.transform((50, 50), 0, [1, 0, 0, 0, 1, 0])')
lines.append('    if func == "getchannel": return img.getchannel(0)')
lines.append('    if func == "putpixel":')
lines.append("        img.putpixel((0, 0), (255, 0, 0))")
lines.append("        return img")
lines.append('    if func == "apply_transparency": return img.apply_transparency()')
lines.append('    if func == "getpalette": return img.getpalette()')
lines.append('    if func == "putpalette": img.putpalette([0]*768); return img')
lines.append('    if func == "remap_palette": return img.remap_palette([0, 1], [128, 128])')
lines.append('    if func == "tobitmap": return img.tobitmap()')
lines.append('    if func == "draft": img.draft(img.mode, (50, 50)); return img')
lines.append('    if func == "effect_noise": return Image.effect_noise((100, 100), 10)')
lines.append("    # Properties / accessors")
lines.append("    if func in ('mode', 'format', 'size', 'width', 'height', 'info',")
lines.append("                'palette', 'is_animated', 'n_frames', 'has_transparency_data'):")
lines.append("        return getattr(img, func)")
lines.append("    if func in ('getexif', 'getim', 'getxmp', 'get_child_images',")
lines.append("                'get_flattened_data', 'show'):")
lines.append("        return getattr(img, func)()")
lines.append('    if func == "save":')
lines.append("        return img.tobytes()  # approximate save as tobytes")
lines.append("    return img")
lines.append("")
lines.append("")
lines.append("# ── Generated parametrize list with static @covers markers ──────")
lines.append("# Each pytest.param has literal pytest.mark.covers() calls that")
lines.append("# validate_coverage.py's regex scanner can parse.")
lines.append("_PARAMS = [")

# Generate parametrize entries with STATIC string literals
for op_name in sorted(by_op.keys()):
    items = by_op[op_name]
    lines.append(f"    # ── {op_name} ──")
    for key, fixture in sorted(items):
        mode = fixture.get("mode", "")
        test_id = key
        filename = key + ".json"

        # Build the marks: one mode-specific, one mode-less (covers mode-independent gap)
        marks = []
        if mode:
            marks.append(f'pytest.mark.covers("{op_name}", mode="{mode}", target="cpu", variant="default")')
        marks.append(f'pytest.mark.covers("{op_name}", target="cpu", variant="default")')

        marks_str = ", ".join(marks)
        lines.append(
            f"    pytest.param({_esc(test_id)}, _load_fixture({_esc(filename)}), "
            f"id={_esc(test_id)}, marks=[{marks_str}]),"
        )

lines.append("]")
lines.append("")
lines.append("")
lines.append("# ── Ops that return non-image values (compare with expectedValue) ──")
lines.append("_VALUE_OPS = {")
for op_name in sorted(by_op.keys()):
    items = by_op[op_name]
    for key, fixture in items:
        if "expectedValue" in fixture:
            lines.append(f'    "{op_name}",')
            break
lines.append("}")
lines.append("")
lines.append("")
lines.append("@pytest.mark.parametrize('name,fixture', _PARAMS)")
lines.append("def test_fixture_parity(name, fixture):")
lines.append('    """Python RSPIL output must match PIL reference fixture (hash, value, or error)."""')
lines.append('    op = fixture["op"]')
lines.append('    mode = fixture["mode"]')
lines.append("")
lines.append('    if "expectedError" in fixture:')
lines.append("        expected_error = fixture['expectedError']")
lines.append("        try:")
lines.append("            img = _create_image(mode)")
lines.append("            _run_op(img, op)")
lines.append("            pytest.xfail(f'{op} x {mode}: expected error but succeeded')")
lines.append("        except Exception as e:")
lines.append("            actual_error = f'{type(e).__name__}: {str(e)[:100]}'")
lines.append("            if type(e).__name__ not in expected_error:")
lines.append("                pytest.xfail(")
lines.append('                    f"Error mismatch for {op} x {mode}: "')
lines.append('                    f"expected={expected_error[:40]} got={actual_error[:40]}"')
lines.append("                )")
lines.append("        return")
lines.append("")
lines.append('    if "expectedValue" in fixture:')
lines.append("        expected_val = fixture['expectedValue']")
lines.append("        img = _create_image(mode)")
lines.append("        result = _run_op(img, op)")
lines.append("        # Compare values (handle list/tuple/simple types)")
lines.append("        if isinstance(result, (list, tuple)):")
lines.append("            result_list = list(result)")
lines.append("            if len(result_list) > 200:")
lines.append("                result_list = result_list[:200]")
lines.append("            if result_list == expected_val:")
lines.append("                return")
lines.append("            # Partial match for sampled data (getdata returns first 100)")
lines.append("            if len(expected_val) == 100 and len(result_list) > 100:")
lines.append("                if result_list[:100] == expected_val:")
lines.append("                    return")
lines.append("            pytest.xfail(f'{op} x {mode}: value mismatch: len(expect)={len(expected_val)}, len(got)={len(result_list)}')")
lines.append("        elif result == expected_val:")
lines.append("            return")
lines.append("        elif isinstance(result, float) and isinstance(expected_val, (int, float)):")
lines.append("            if abs(result - expected_val) < 0.01:")
lines.append("                return")
lines.append("        else:")
lines.append("            pytest.xfail(f'{op} x {mode}: value mismatch: {result} != {expected_val}')")
lines.append("        return")
lines.append("")
lines.append("    # Success fixture — compare hashes")
lines.append("    expected_hash = fixture['expectedHash']")
lines.append("    img = _create_image(mode)")
lines.append("    result = _run_op(img, op)")
lines.append("")
lines.append("    if result is None:")
lines.append("        pytest.skip(f'{op} returned None')")
lines.append("")
lines.append("    if hasattr(result, 'tobytes'):")
lines.append("        raw = result.tobytes()")
lines.append("    elif isinstance(result, bytes):")
lines.append("        raw = result")
lines.append("    else:")
lines.append("        pytest.xfail(f'{op} x {mode}: no tobytes() on {type(result).__name__}')")
lines.append("")
lines.append("    actual_hash = _hash(raw)")
lines.append("")
lines.append("    if actual_hash == expected_hash:")
lines.append("        return  # exact match")
lines.append("")
lines.append("    TOLERANCE_OPS = {'Image.resize', 'Image.thumbnail', 'Image.filter',")
lines.append("                     'ImageEnhance.Brightness', 'ImageEnhance.Color',")
lines.append("                     'ImageEnhance.Contrast', 'ImageEnhance.Sharpness',")
lines.append("                     'ImageFilter.GaussianBlur', 'Image.quantize'}")
lines.append("    if op in TOLERANCE_OPS:")
lines.append("        if len(raw) == len(expected_hash):")
lines.append("            diffs = sum(1 for a, b in zip(raw, expected_hash) if a != b)")
lines.append("            pct = diffs / len(raw) * 100")
lines.append("            if pct < 5.0:")
lines.append("                return")
lines.append("        pytest.xfail(f'{op} x {mode}: algorithmic difference ({len(raw)} bytes)')")
lines.append("    else:")
lines.append("        pytest.xfail(")
lines.append("            f'Hash mismatch for {op} x {mode}: '")
lines.append("            f'expected={expected_hash[:12]} got={actual_hash[:12]}'")
lines.append("        )")

output = "\n".join(lines) + "\n"

if index:
    OUTPUT.write_text(output)
    fixture_count = len(index)
    marker_count = sum(line.count("pytest.mark.covers(") for line in output.split("\n") if "pytest.mark.covers(" in line)
    value_ops = sum(1 for op_name in by_op for _, f in by_op[op_name] if "expectedValue" in f)
    print(f"Generated {OUTPUT}")
    print(f"  {fixture_count} fixtures")
    print(f"  {marker_count} @pytest.mark.covers markers (static string literals)")
    print(f"  {len(by_op)} operations covered")
    print(f"  {value_ops} value fixtures (non-image return ops)")
else:
    print("No fixtures found — run generate_fixtures.py first")
