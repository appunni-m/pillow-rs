lines.append("        except Exception as e:")
lines.append("            actual_error = f'{type(e).__name__}: {str(e)[:100]}'")
lines.append("            if type(e).__name__ not in expected_error:")
lines.append("                pytest.xfail(")
lines.append('                    f"Error mismatch for {op} x {mode}: "')
lines.append('                    f"expected={expected_error[:40]} got={actual_error[:40]}"')
lines.append("                )")
lines.append("        return")
lines.append("")
lines.append('    if "expectedValue" in fixture:')
lines.append("        expected_val = fixture['expectedValue']")
lines.append("        img = _make_input(fixture)")
lines.append("        if img is None:")
lines.append("            pytest.xfail(f'Cannot create input for {mode}')")
lines.append("        result = _run_op(img, op)")
lines.append("        if isinstance(result, (list, tuple)):")
lines.append("            result_list = list(result)")
lines.append("            if result_list == expected_val:")
lines.append("                return")
lines.append("            if isinstance(expected_val, (list, tuple)) and len(expected_val) <= 100 and len(result_list) > len(expected_val):")
lines.append("                if result_list[:len(expected_val)] == expected_val:")
lines.append("                    return")
lines.append("            if isinstance(expected_val, (list, tuple)) and len(expected_val) > 200 and len(result_list) == len(expected_val):")
lines.append("                diffs = sum(1 for i in range(len(expected_val)) if result_list[i] != expected_val[i])")
lines.append("                if diffs == 0:")
lines.append("                    return  # identical but missed by Python list equality")
lines.append("            pytest.xfail(f'{op} x {mode}: value mismatch: len(e)={len(expected_val) if hasattr(expected_val, \"__len__\") else \"?\"}, got type={type(result).__name__}')")
lines.append("        elif result == expected_val:")
lines.append("            return")
lines.append("        elif isinstance(result, float) and isinstance(expected_val, (int, float)):")
lines.append("            if abs(result - expected_val) < 0.01:")
lines.append("                return")
lines.append("        else:")
lines.append("            pytest.xfail(f'{op} x {mode}: value mismatch: {type(result).__name__}={result!r} vs {type(expected_val).__name__}={expected_val!r}')")
lines.append("        return")
lines.append("")
lines.append("    # Success fixture — compare hashes")
lines.append("    expected_hash = fixture['expectedHash']")
lines.append("    img = _make_input(fixture)")
lines.append("    if img is None:")
lines.append("        pytest.xfail(f'Cannot create input image for mode {mode}')")
lines.append("    try:")
lines.append("        result = _run_op(img, op)")
lines.append("    except NotImplementedError as e:")
lines.append("        pytest.xfail(f'{op} x {mode}: {e}')")
